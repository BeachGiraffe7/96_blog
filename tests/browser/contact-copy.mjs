const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
import fs from 'node:fs/promises'
import assert from 'node:assert/strict'
const out=process.env.QA_OUTPUT_DIR || '/data/contact-copy-qa'
await fs.mkdir(out,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/local/bin/chromium',headless:true,args:['--no-sandbox']})
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}})
 await context.addInitScript(()=>{
  localStorage.setItem('blog_palette','sage');localStorage.setItem('blog_theme','light')
  Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{if(window.__failCopy)throw Error('blocked');window.__copied=text}}})
 })
 const p=await context.newPage(), errors=[]
 p.on('pageerror',e=>errors.push(e.message))
 const base=process.env.QA_BASE_URL || 'http://127.0.0.1:5173'
 async function shot(locator,name){await p.waitForTimeout(350);assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await locator.screenshot({path:`${out}/${name}.png`})}
 await p.goto(base+'/about')
 await p.locator('.about-contact').waitFor()
 assert.equal(await p.locator('a[href^="mailto:"]').count(),0)
 assert.deepEqual(await p.locator('.about-contact .contact-options > *').evaluateAll(els=>els.map(el=>el.querySelector('strong').textContent)),['QQ 邮箱','GitHub','微信'])
 await p.getByRole('button',{name:'复制邮箱地址',exact:true}).click()
 assert.equal(await p.evaluate(()=>window.__copied),'1502765800@qq.com')
 assert.equal(await p.locator('.about-contact [role=status]').innerText(),'邮箱地址已复制')
 await shot(p.locator('.about-contact'),'about-contact-desktop-light')
 await p.evaluate(async()=>{const t=await import('/src/lib/theme.js');t.setTheme('dark')})
 await shot(p.locator('.about-contact'),'about-contact-desktop-dark')
 await p.setViewportSize({width:390,height:844})
 await shot(p.locator('.about-contact'),'about-contact-mobile-dark')
 await p.evaluate(async()=>{const t=await import('/src/lib/theme.js');t.setTheme('light')})
 await shot(p.locator('.about-contact'),'about-contact-mobile-light')
 await p.goto(base+'/')
 const card=p.locator('.profile-card')
 await card.waitFor()
 assert.deepEqual(await card.locator('.contact-options > *').evaluateAll(els=>els.map(el=>el.getAttribute('aria-label'))),['查看QQ 邮箱联系方式','GitHub 个人主页','查看微信联系方式'])
 await card.getByRole('button',{name:'查看QQ 邮箱联系方式',exact:true}).click()
 assert.equal(await card.locator('.contact-id').innerText(),'1502765800@qq.com')
 await card.getByRole('button',{name:'复制邮箱地址',exact:true}).click()
 assert.equal(await card.locator('[role=status]').innerText(),'邮箱地址已复制')
 assert.equal(await p.evaluate(()=>window.__copied),'1502765800@qq.com')
 await shot(card,'profile-email-copy')
 await p.evaluate(()=>{window.__failCopy=true})
 await card.getByRole('button',{name:'复制邮箱地址',exact:true}).click()
 assert.equal(await card.locator('[role=status]').innerText(),'未能自动复制，请选中邮箱地址手动复制。')
 await shot(card,'profile-email-fallback')
 await card.getByRole('button',{name:'查看微信联系方式',exact:true}).click()
 assert.equal(await card.locator('.contact-detail-panel').count(),1)
 assert.equal(await card.locator('.contact-id').innerText(),'Dec21_Hello')
 assert.equal(await card.getByRole('button',{name:'查看QQ 邮箱联系方式',exact:true}).getAttribute('aria-expanded'),'false')
 await p.evaluate(()=>{window.__failCopy=false})
 await card.getByRole('button',{name:'复制微信号',exact:true}).click()
 assert.equal(await p.evaluate(()=>window.__copied),'Dec21_Hello')
 await card.getByRole('button',{name:'查看微信联系方式',exact:true}).click()
 assert.equal(await card.locator('.contact-detail-panel').count(),0)
 assert.deepEqual(errors,[])
 console.log('PASS email and WeChat copy, denied-clipboard fallback, mutually exclusive panels, GitHub centered, no mailto links, desktop/mobile light/dark, no overflow or JS errors')
 await context.close()
}finally{await browser.close()}
